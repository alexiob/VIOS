"""PlatformIO pre-build: embed the current RAM image, never alter target hardware."""
Import('env')
from pathlib import Path
import hashlib
import json
import os
import zlib
project=Path(env.subst('$PROJECT_DIR'))
root=project.parents[1]
image=Path(os.environ.get('VIOS_IMAGE',str(root/'build/vios-resident.bin'))).expanduser().resolve()
baud=int(os.environ.get('VIOS_INTERNAL_BAUD','1152000'))
if baud not in (115200,384000,1152000):
    raise RuntimeError('Unsupported internal UART baud: '+str(baud))
rate_path=image.with_suffix('.baud')
if not rate_path.exists() or rate_path.read_text().strip()!=str(baud):
    raise RuntimeError('Resident/ESP internal baud mismatch; rebuild resident with VIOS_INTERNAL_BAUD='+str(baud)+' and preserve its .baud sidecar')
env.Append(CPPDEFINES=[('VIOS_INTERNAL_BAUD',baud)])
# include/vios/version.h must match VERSION (make vios-resident or tools/vios_release.py sync writes it).
version=(root/'VERSION').read_text().strip()
if f'#define VIOS_VERSION "{version}"' not in (root/'include/vios/version.h').read_text():
    raise RuntimeError('include/vios/version.h does not match VERSION '+version+'; run tools/vios_release.py sync')
# GUI pairing: a GUI-booting VDP needs a resident built with VIOS_GUI=1 (its
# workbench draws through the display server) and the text VDP the opposite.
gui=os.environ.get('VIOS_GUI','1')
if gui not in ('0','1'):
    raise RuntimeError('VIOS_GUI must be 0 or 1')
gui_path=image.with_suffix('.gui')
if not gui_path.exists() or gui_path.read_text().strip()!=gui:
    raise RuntimeError('Resident/ESP GUI mismatch; rebuild resident with VIOS_GUI='+gui+' and preserve its .gui sidecar')
env.Append(CPPDEFINES=[('VIOS_GUI_BOOT',int(gui))])
data=image.read_bytes()
if not data or len(data)>0x6F000 or data[64:69]!=b'MOS\0\1':
    raise RuntimeError('Build a valid bounded resident image before the VDP image: '+str(image))
out=project/'include/vios_image.h'
content='/* Generated by scripts/embed_vios.py. */\n#include <stdint.h>\n'
content+=f'static const unsigned vios_image_size = {len(data)};\n'
content+=f'static const uint32_t vios_image_crc = 0x{__import__("zlib").crc32(data):08x}UL;\n'
content+=f'static const char vios_image_sha256[] = "{hashlib.sha256(data).hexdigest()}";\n'
content+='static const uint8_t vios_image[] PROGMEM = {\n'
content+='\n'.join(','.join(f'0x{x:02x}' for x in data[i:i+24])+',' for i in range(0,len(data),24))+'\n};\n'
if not out.exists() or out.read_text()!=content:out.write_text(content)
env.Append(CPPPATH=[str(root/'include')])
embedded={'path':str(image.relative_to(root)) if image.is_relative_to(root) else str(image),'size':len(data),'sha256':hashlib.sha256(data).hexdigest(),'crc32':f'{zlib.crc32(data):08x}','internal_baud':baud,'gui':int(gui)}
(project/'include/vios_image.json').write_text(json.dumps(embedded,indent=2)+'\n')

stage_path=root/'build/agon-stage0.bin'
stage=stage_path.read_bytes()
if not stage or len(stage)>256:
    raise RuntimeError('Build bounded build/agon-stage0.bin before the VDP image')
stage_content='/* Generated native RAM bootstrap; no CPU flash writes. */\n#pragma once\n#include <stdint.h>\n'
stage_content+=f'static const unsigned vios_stage0_size = {len(stage)};\n'
stage_content+='static const uint8_t vios_stage0[] PROGMEM = {'+','.join(f'0x{x:02x}' for x in stage)+'};\n'
crc_stage=(root/'build/agon-crc.bin').read_bytes() if (root/'build/agon-crc.bin').is_file() else b''
if not crc_stage or len(crc_stage)>256:
    raise RuntimeError('Build bounded build/agon-crc.bin before the VDP image')
stage_content+=f'static const unsigned vios_crc_stage_size = {len(crc_stage)};\n'
stage_content+='static const uint8_t vios_crc_stage[] PROGMEM = {'+','.join(f'0x{x:02x}' for x in crc_stage)+'};\n'
stage_out=project/'include/vios_stage0.h'
if not stage_out.exists() or stage_out.read_text()!=stage_content:stage_out.write_text(stage_content)
flash_stage=(root/'build/agon-flash.bin').read_bytes() if (root/'build/agon-flash.bin').is_file() else b''
if not flash_stage or len(flash_stage)>256:
    raise RuntimeError('Build bounded build/agon-flash.bin before the VDP image')
flash_content='/* Generated eZ80 flash programmer (arch/ez80/agon_flash.s), run only by MF over ZDI. */\n#pragma once\n#include <stdint.h>\n'
flash_content+=f'static const unsigned vios_flash_stage_size = {len(flash_stage)};\n'
flash_content+='static const uint8_t vios_flash_stage[] PROGMEM = {'+','.join(f'0x{x:02x}' for x in flash_stage)+'};\n'
flash_out=project/'include/vios_flash_stage.h'
if not flash_out.exists() or flash_out.read_text()!=flash_content:flash_out.write_text(flash_content)
(project/'include/vios_stage0.json').write_text(json.dumps({'path':'build/agon-stage0.bin','size':len(stage),'sha256':hashlib.sha256(stage).hexdigest(),
    'crc_stage':{'path':'build/agon-crc.bin','size':len(crc_stage),'sha256':hashlib.sha256(crc_stage).hexdigest()}},indent=2)+'\n')
