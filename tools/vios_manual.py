KIND = {0: 'primitive', 1: 'colon', 2: 'constant', 3: 'variable', 4: 'defer', 5: 'native', 6: 'does', 7: 'marker'}
PUNCT = {'!': 'store', '@': 'fetch', '#': 'num', '"': 'q', "'": 'tick', '(': 'lp', ')': 'rp', '*': 'star', '+': 'plus',
         ',': 'comma', '-': '-', '.': 'dot', '/': 'slash', ':': 'colon', ';': 'semi', '<': 'lt', '=': 'eq', '>': 'gt',
         '?': 'q', '[': 'lb', ']': 'rb', '\\': 'bs'}


def slug(name):
    """Anchor of a word: w- + its name with punctuation spelled out (DUP -> w-dup, C@ -> w-cfetch)."""
    out = ''.join(c if c.isalnum() else PUNCT.get(c, '') for c in name.lower())
    return 'w-' + out


def run(cmd, **kw):
    return subprocess.run(cmd, cwd=ROOT, check=True, **kw)


def agon_font():
    """The device's 8x8 font as 256 glyphs (the vendored bitmap starts at space)."""
    text = (ROOT / 'firmware/esp32-vios/vendor/agon-vdp/video/agon_fonts.h').read_text(encoding='latin-1')
    body = text[text.index('FONT_AGON_BITMAP[]'):]
    body = body[body.index('{') + 1:body.index('};')]
    data = bytes(int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{2})', body))
    return bytes(32 * 8) + data[:(256 - 32) * 8]


def build():
    BUILD.mkdir(parents=True, exist_ok=True)
    flags = ['cc', '-std=c99', '-Wall', '-Wextra', '-O1', '-Iinclude']
    (BUILD / 'font.bin').write_bytes(agon_font())
    run(flags + ['-I' + VDS, 'tools/manual/vios_doc_host.c', *RUNTIME, *ESP, '-o', str(BUILD / 'vios_doc_host')])
    run(flags + ['-I' + VDS, 'tools/manual/vios_shots.c', *SHOTS, '-o', str(BUILD / 'vios_shots')])


def doc_host(*args, stdin=None):
    with tempfile.TemporaryDirectory() as root:
        (Path(root) / 'VIOS').mkdir()
        (Path(root) / 'HOSTSHARE').mkdir()
        return subprocess.run([str(BUILD / 'vios_doc_host'), root, *args, str(BUILD / 'font.bin')], input=stdin, capture_output=True,
                              text=True, cwd=ROOT, timeout=120)


# ---------------------------------------------------------------- word list

def source_words():
    """{name: (kind, definition)} for every word the system accepts, from the sources."""
    words = {}
    out = doc_host('--inspect')
    if out.returncode:
        sys.exit('vios_doc_host --inspect failed: ' + out.stderr)
    prelude = set(re.findall(r':\s+(\S+)', (ROOT / 'kernel/vios_prelude.c').read_text()))
    for line in out.stdout.splitlines():
        name, kind, source = (line.split('\t') + ['', ''])[:3]
        kind = KIND.get(int(kind), 'word')
        if kind == 'colon' and name in prelude:
            kind = 'prelude'
        words.setdefault(name, (kind, source.strip()))
    system = (ROOT / 'forth/system.c').read_text()
    parsed = re.findall(r'equal\(s,"((?:[^"\\]|\\.)*)"\)', system)
    table = re.search(r'keywords\[KW_COUNT\]=\{(.*?)\n\};', system, re.S)       # newer compilers keep a table
    if table:
        parsed += re.findall(r'\{"((?:[^"\\]|\\.)*)",', table.group(1))
    for name in parsed:
        words.setdefault(name.replace('\\"', '"').replace('\\\\', '\\'), ('compiler', ''))
    # Comments are parsed while skipping white space (forth/system.c).
    if "**p=='('" in system:
        words.setdefault('(', ('compiler', ''))
    if "**p=='\\\\'" in system:
        words.setdefault('\\', ('compiler', ''))
    for path in sorted((ROOT / 'kernel').glob('*.c')):
        for name in re.findall(r'vios_same\(word,"([^"]+)"\)', path.read_text()):
            words.setdefault(name, ('command', ''))
    irq = (ROOT / 'kernel/vios_irq.c').read_text()
    for name in re.findall(r'forth_register_native\("([^"]+)"', irq):
        words.setdefault(name, ('native', ''))
    return words


def curated():
    entries, problems = {}, []
    for path in sorted(WORDS_DIR.glob('*.toml')):
        data = tomllib.loads(path.read_text())
        for e in data.get('word', []):
            name = e.get('name')
            if name in entries:
                problems.append(f'{path.name}: {name} described twice')
            for field in ('name', 'section', 'effect', 'desc'):
                if not e.get(field):
                    problems.append(f'{path.name}: {name}: missing {field}')
            if e.get('section') not in SECTIONS:
                problems.append(f'{path.name}: {name}: unknown section {e.get("section")!r}')
            entries[name] = e
    return entries, problems


def check():
    words, (entries, problems) = source_words(), curated()
    for name in words:
        if name not in entries:
            problems.append(f'undocumented word: {name}')
    for name in entries:
        if name not in words:
            problems.append(f'documented but not in the sources: {name}')
    for p in problems:
        print(p)
    print(f'{len(words)} words in the sources, {len(entries)} documented, {len(problems)} problems')
    return not problems


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def code(text):
    """Inline code that survives backticks in the text."""
    fence = '``' if '`' in text else '`'
    pad = ' ' if text.startswith('`') or text.endswith('`') else ''
    return f'{fence}{pad}{text}{pad}{fence}'


def render_reference():
    words, (entries, _) = source_words(), curated()
    lines = [BEGIN, '',
             f'This reference lists all {len(words)} words that VIOS accepts, generated from the sources by '
             '`tools/vios_manual.py words`. **Kind** is how the word is made: *primitive* (a VM opcode), *native* '
             '(a C function), *prelude* or *colon* (defined in Forth; the definition is shown), *constant*, '
             '*variable*, *defer* (a replaceable binding), *compiler* (parsed by the outer interpreter) or '
             '*command* (a line command parsed by the kernel; the rest of the line is its argument). '
             'Words marked **board** do real work only on the board (on the host build they talk to stubs).',
             '']
    by_section = {k: [] for k in SECTIONS}
    for name, e in entries.items():
        if name in words:
            by_section[e['section']].append(e)
    lines.append('**Sections:** ' + ' · '.join(f'[{SECTIONS[k][0]}](#ref-{k})'
                                                  for k, v in by_section.items() if v))
    lines.append('')
    for key, items in by_section.items():
        if not items:
            continue
        title, intro = SECTIONS[key]
        lines += [f'<a id="ref-{key}"></a>', '', f'### {title}', '', intro, '', '| Word | Stack effect | Description | Kind |', '| --- | --- | --- | --- |']
        for e in items:
            kind, source = words[e['name']]
            desc = cell(e['desc'].strip())
            if e.get('example'):
                desc += ' Example: ' + code(cell(e['example'].strip()))
            if kind in ('prelude', 'colon') and source and len(source) < 90:
                desc += ' Definition: ' + code(cell(source))
            tag = kind + (', board' if e.get('board') else '')
            lines.append(f'| <a id="{slug(e["name"])}"></a>{code(cell(e["name"]))} | {code(cell(e["effect"].strip()))} '
                         f'| {desc} | {tag} |')
        lines.append('')
    lines += ['### Index of words', '', 'All words in ASCII order:', '']
    lines.append(' '.join(f'[{code(cell(n))}](#{slug(n)})' for n in sorted(words) if n in entries))
    lines += ['', END]
    return '\n'.join(lines)


def words_cmd():
    text = MANUAL.read_text()
    if BEGIN not in text or END not in text:
        sys.exit(f'{MANUAL} lacks the word reference markers')
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    MANUAL.write_text(head + render_reference() + tail)
    print('word reference written')


# ---------------------------------------------------------------- examples

def examples():
    """Run every ```forth block, chapter by chapter (a fresh system per chapter)."""
    text = MANUAL.read_text().split('\n')
    chapters, chapter, block, skip, start = [], None, None, False, 0
    for i, line in enumerate(text, 1):
        if block is not None:
            if line.startswith('```'):
                if not skip:
                    chapter[1].append((start, '\n'.join(block)))
                block, skip = None, False
            else:
                block.append(line)
            continue
        if line.startswith('## '):
            chapter = (line[3:].strip(), [])
            chapters.append(chapter)
        elif line.strip() == '```forth' and chapter:
            block, start = [], i
            skip = text[i - 2].strip() == '<!-- nocheck -->' if i >= 2 else False
        elif line.startswith('```'):
            block, skip = [], True
    failures = total = 0
    for title, blocks in chapters:
        if not blocks:
            continue
        stdin = ''.join(f'#BLOCK {line}\n{body}\n' for line, body in blocks)
        out = doc_host('--check', stdin=stdin)
        results = re.findall(r'#RESULT (\d+) (ok|FAIL) ?(.*)', out.stdout)
        total += len(blocks)
        if len(results) != len(blocks):
            print(f'{title}: the host stopped early ({len(results)}/{len(blocks)}): {out.stderr.strip()[-300:]}')
            failures += len(blocks) - len(results)
        for line, status, error in results:
            if status != 'ok':
                failures += 1
                print(f'VIOS-MANUAL.md:{line}: {title}: {error}')
    print(f'{total} forth blocks run, {failures} failed')
    return not failures


# ---------------------------------------------------------------- media

def expand(lines):
    """Animation macros: `ktype TEXT` types on the keyboard and `ctype TEXT` at the
    console, one frame per character. `include NAME` inserts scenes/NAME.inc."""
    for line in lines:
        cmd, _, text = line.partition(' ')
        if cmd == 'include':
            yield from expand((SCENES / (text.strip() + '.inc')).read_text().splitlines())
            continue
        if cmd not in ('ktype', 'ctype'):
            yield line
            continue
        text = text.replace('\\n', '\n')
        for c in text:
            yield ('type ' if cmd == 'ktype' else 'conraw ') + c.replace('\\', '\\\\').replace('\n', '\\n')
            yield 'frame 90'


def media(only=None):
    """Each scene renders its `shot NAME` stills to media/NAME.png; a scene with
    `frame MS` lines also becomes media/SCENE.gif, each frame shown MS ms."""
    for tool in ('magick', 'gifsicle'):
        if not shutil.which(tool):
            sys.exit(f'{tool} is needed for media')
    MEDIA.mkdir(parents=True, exist_ok=True)
    for scene in sorted(SCENES.glob('*.scene')):
        if only and scene.stem not in only:
            continue
        lines, delays = [], []
        for line in expand(scene.read_text().splitlines()):
            if line.startswith('frame'):
                parts = line.split()
                delays.append(int(parts[1]) if len(parts) > 1 else 300)
                lines.append(f'shot _frame{len(delays):03d}')
            else:
                lines.append(line)
        with tempfile.TemporaryDirectory() as out:
            if any(l.strip() == 'runtime full' for l in lines):
                # The whole resident runtime (handles, files, /dev/win) on the
                # real display server: eval lines are blocks, shots dump the screen.
                unescape = lambda t: re.sub(r'\\(.)', lambda m: '\n' if m.group(1) == 'n' else m.group(1), t)
                blocks = [f'#BLOCK @shot {out}/{l[5:].strip()}.ppm' if l.startswith('shot ') else f'#BLOCK {k}\n{unescape(l[5:])}'
                          for k, l in enumerate(lines) if l.startswith(('eval ', 'shot '))]
                result = doc_host('--check', stdin='\n'.join(blocks) + '\n')
                failed = re.findall(r'#RESULT (\S+) FAIL (.*)', result.stdout)
                if failed:
                    sys.exit(f'{scene.name}: line {failed[0][0]}: {failed[0][1]}')
            else:
                result = subprocess.run([str(BUILD / 'vios_shots'), str(BUILD / 'font.bin'), out],
                                        input='\n'.join(lines) + '\n', text=True, capture_output=True, cwd=ROOT)
            if result.returncode:
                sys.exit(f'{scene.name}: {result.stderr.strip()}')
            for ppm in sorted(Path(out).glob('*.ppm')):
                if ppm.stem.startswith('_frame'):
                    run(['magick', str(ppm), str(ppm.with_suffix('.gif'))])
                else:
                    png = MEDIA / (ppm.stem + '.png')
                    run(['magick', str(ppm), '-strip', '-define', 'png:exclude-chunks=date,time', 'PNG8:' + str(png)])
                    print('  ', png.relative_to(ROOT))
            if delays:
                gif = MEDIA / (scene.stem + '.gif')
                cmd = ['gifsicle', '-O3', '--loopcount=forever', '-o', str(gif)]
                for k, ms in enumerate(delays, 1):
                    cmd += ['-d', str(max(2, ms // 10)), str(Path(out) / f'_frame{k:03d}.gif')]
                run(cmd)
                print('  ', gif.relative_to(ROOT), f'({len(delays)} frames, {gif.stat().st_size // 1024} KB)')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('command', choices=('build', 'words', 'check', 'examples', 'media', 'all'))
    ap.add_argument('scenes', nargs='*', help='media: only these scenes (file stems)')
    a = ap.parse_args()
    if a.command in ('build', 'all') or not (BUILD / 'vios_doc_host').exists() or not (BUILD / 'vios_shots').exists():
        build()
    ok = True
    if a.command in ('check', 'all'):
        ok = check() and ok
    if a.command in ('words', 'all'):
        words_cmd()
    if a.command in ('examples', 'all'):
        ok = examples() and ok
    if a.command in ('media', 'all'):
        media(a.scenes)
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
