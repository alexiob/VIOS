#!/usr/bin/env python3
"""Build the VIOS manual's generated parts from the sources, on the host.

  python3 tools/vios_manual.py build      compile the host tools into build/manual
  python3 tools/vios_manual.py words      regenerate the word reference in the manual
  python3 tools/vios_manual.py check      fail if the word list and docs/manual/words/*.toml differ
  python3 tools/vios_manual.py examples   run every ```forth block of the manual on the host Forth
  python3 tools/vios_manual.py media      render docs/manual/scenes/*.scene into docs/manual/media
  python3 tools/vios_manual.py all        all of the above, in order

The word list comes from the real system: the dictionary of a host build of
the resident runtime (tools/manual/vios_doc_host.c), the words the outer
interpreter parses in forth/system.c, the commands parsed by kernel/*.c and
the board-only natives of kernel/vios_irq.c. Descriptions and stack effects
are curated in docs/manual/words/*.toml; `check` keeps the two in step.
Screenshots come from the real GUI code (tools/manual/vios_shots.c). Nothing
here touches the board. Needs cc; media also needs ImageMagick and gifsicle.
"""
