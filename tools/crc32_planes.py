"""Write the reflected CRC-32 table as four 256-byte planes (plane k = byte k of
each entry) as GNU as `.byte` lines, for the eZ80 plane CRC loops."""
import sys


def planes():
    table = []
    for n in range(256):
        c = n
        for _ in range(8):
            c = (c >> 1) ^ (0xEDB88320 if c & 1 else 0)
        table.append(c)
    return [[(entry >> (8 * k)) & 255 for entry in table] for k in range(4)]


if __name__ == '__main__':
    lines = ['/* Generated by tools/crc32_planes.py: CRC-32 table planes 0..3. */']
    for plane in planes():
        for i in range(0, 256, 16):
            lines.append('    .byte ' + ','.join(f'0x{b:02X}' for b in plane[i:i + 16]))
    open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
